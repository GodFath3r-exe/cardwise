/**
 * Regenerates db/seed.sql from assets/js/cards-data.js
 * Run: node db/generate-seed.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import vm from "vm";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const dataPath = path.join(root, "assets/js/cards-data.js");
const outPath = path.join(__dirname, "seed.sql");

const src = fs.readFileSync(dataPath, "utf8");
const sandbox = { window: {} };
vm.runInNewContext(src, sandbox);
const cards = sandbox.window.CARDWISE_CARDS || [];

function sqlStr(v) {
  if (v == null) return "NULL";
  return `'${String(v).replace(/'/g, "''")}'`;
}

function sqlNum(v) {
  if (v == null || v === "") return "NULL";
  return String(v);
}

const lines = [
  "-- Reset CardWise catalog to top India cards",
  "-- Generated by db/generate-seed.mjs — do not edit by hand",
  "begin;",
  "truncate source_urls, card_sources, card_offers, cards restart identity cascade;",
  "",
];

for (const c of cards) {
  lines.push(`insert into cards (
  id, name, short_name, bank, network, tagline, best_for, card_group,
  joining_fee, annual_fee, waiver, fee_hint, earn_label, accent, gradient
) values (
  ${sqlStr(c.id)}, ${sqlStr(c.name)}, ${sqlStr(c.shortName)}, ${sqlStr(c.bank)}, ${sqlStr(c.network)},
  ${sqlStr(c.tagline)}, ${sqlStr(c.bestFor)}, ${sqlStr(c.group || "popular")},
  ${sqlStr(c.joiningFee)}, ${sqlStr(c.annualFee)}, ${sqlStr(c.waiver)}, ${sqlStr(c.feeHint)},
  ${sqlStr(c.earnLabel || "cashback")}, ${sqlStr(c.accent)}, ${sqlStr(c.gradient)}
);`);
  lines.push("");

  (c.offers || []).forEach((o, i) => {
    lines.push(`insert into card_offers (
  card_id, sort_order, title, rate, rate_value, cap_label, cap_amount, cap_period, tier, hint
) values (
  ${sqlStr(c.id)}, ${i}, ${sqlStr(o.title)}, ${sqlStr(o.rate)}, ${sqlNum(o.rateValue)},
  ${sqlStr(o.capLabel)}, ${sqlNum(o.capAmount)}, ${sqlStr(o.capPeriod)},
  ${sqlStr(o.tier)}, ${sqlStr(o.hint)}
);`);
    lines.push("");
  });

  for (const s of c.sources || []) {
    lines.push(`insert into card_sources (card_id, label, url) values (
  ${sqlStr(c.id)}, ${sqlStr(s.label)}, ${sqlStr(s.url)}
);`);
    lines.push("");
    lines.push(`insert into source_urls (card_id, url, kind) values (
  ${sqlStr(c.id)}, ${sqlStr(s.url)}, 'official'
) on conflict (card_id, url) do nothing;`);
    lines.push("");
  }
}

lines.push("commit;");
fs.writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`Wrote ${cards.length} cards → ${outPath}`);
